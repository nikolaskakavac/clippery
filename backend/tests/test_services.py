URL = 'https://youtu.be/dQw4w9WgXcQ'
def finish(manager, job_id):
    for _ in range(200):
        result = manager.public(job_id)
        if result['state'] in {'Ready', 'Failed'}: return result
        time.sleep(.01)
    pytest.fail('Job did not finish')

@pytest.fixture
def manager(tmp_path, monkeypatch):
    monkeypatch.setattr('app.services.storage.JOB_ROOT', tmp_path)
    monkeypatch.setattr(jobs, 'JOB_ROOT', tmp_path)
    instance = JobManager()
    yield instance
    instance.pool.shutdown(wait=True)

def test_delivery_cleanup(manager, monkeypatch):
    monkeypatch.setattr(jobs, 'extract', lambda _: {'duration':20})
    def process(url, quality, directory, update):
        path = directory / 'clipper.mp4'; path.write_bytes(b'video'); return path
    monkeypatch.setattr(jobs, 'process', process)
    job = manager.submit(DownloadRequest(url=URL))
    assert finish(manager, job['id'])['state'] == 'Ready'
    path = manager.acquire(job['id'])
    manager.cleanup()
    assert path.exists()
    manager.release(job['id'])
    assert not path.exists()
    assert manager.public(job['id']) is None

