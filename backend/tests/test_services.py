def test_manual_captions_preferred(monkeypatch):
    import io, json
    monkeypatch.setattr(transcript_service, 'extract', lambda _: {
        'duration':100, 'subtitles':{'pl':[{'ext':'json3','url':'https://www.youtube.com/api/timedtext'}]},
        'automatic_captions':{'en':[{'ext':'json3','url':'https://www.youtube.com/api/timedtext'}]}})
    class FakeYDL:
        def __init__(self, opts): pass
        def __enter__(self): return self
        def __exit__(self, *args): pass
        def urlopen(self, url): return io.BytesIO(json.dumps({'events':[{'tStartMs':1250,'dDurationMs':2000,'segs':[{'utf8':'Hello'}]}]}).encode())
    monkeypatch.setattr(transcript_service, 'YoutubeDL', FakeYDL)
    result = transcript_service.provider.get(URL)
    assert result['language'] == 'pl' and result['isAutoGenerated'] is False
    assert result['segments'][0]['start'] == 1.25
    assert result['segments'][0]['end'] == 3.25

def test_section_fallback_stays_bounded(tmp_path, monkeypatch):
    from app.services import download_service as service
    monkeypatch.setattr(service.shutil, 'which', lambda _: 'tool')
    attempts = []
    class FakeYDL:
        def __init__(self, opts): self.opts = opts
        def __enter__(self): return self
        def __exit__(self, *args): pass
        def download(self, urls):
            attempts.append(dict(self.opts))
            (tmp_path / 'source.mp4').write_bytes(b'source')
    monkeypatch.setattr(service, 'YoutubeDL', FakeYDL)
    monkeypatch.setattr(service, 'editor_mp4', lambda source, output, update: output.write_bytes(b'mp4'))
    monkeypatch.setattr(service, 'usable_section', lambda path, duration: len(attempts) == 2)
    result = service.process(URL, '1080', tmp_path, lambda *args: None, section=(5, 10))
    assert result.exists() and len(attempts) == 2
    assert attempts[0]['force_keyframes_at_cuts'] is False
    assert attempts[1]['force_keyframes_at_cuts'] is True
    assert attempts[0]['download_ranges'] is attempts[1]['download_ranges']
    assert list(attempts[1]['download_ranges']({}, None)) == [{'start_time':5, 'end_time':10}]

def test_good_section_avoids_reencoding(tmp_path, monkeypatch):
    from app.services import download_service as service
    monkeypatch.setattr(service.shutil, 'which', lambda _: 'tool')
    attempts = []
    class FakeYDL:
        def __init__(self, opts): attempts.append(dict(opts))
        def __enter__(self): return self
        def __exit__(self, *args): pass
        def download(self, urls): (tmp_path / 'source.mp4').write_bytes(b'source')
    monkeypatch.setattr(service, 'YoutubeDL', FakeYDL)
